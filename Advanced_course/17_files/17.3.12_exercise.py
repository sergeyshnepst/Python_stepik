"""
Вам доступен текстовый файл, каждая строка которого может содержать одно или несколько целых чисел, разделенных одним или несколькими пробелами.

Напишите программу, которая принимает на вход строку с именем текстового файла, вычисляет сумму чисел в каждой строке этого файла и выводит эту сумму на экран (для каждой строки сумма чисел выводится в отдельной строке).

Формат входных данных
На вход программе подается строка текста с именем существующего текстового файла.

Формат выходных данных
Программа должна вывести сумму чисел для каждой строки.
"""

with open(input(), 'r', encoding='utf-8') as file:
    lines_list = file.readlines()
    for line in lines_list:
        line = [int(i) for i in line.split()]
        print(sum(line))