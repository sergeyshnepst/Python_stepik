"""
Есть три продуктовых магазина: «Десяточка», «Кубит» и «Полоса». Для каждого магазина есть текстовый файл, в котором указаны доступные продукты и цены на них. Каждая строка такого файла представлена в следующем формате:

<продукт>: <цена>
                 
Название текстового файла для магазина «Десяточка» – desyatochka.txt, для магазина «Кубит» – kubit.txt, для магазина «Полоса» – polosa.txt.

На вход программе подается натуральное число n, а затем n продуктов для покупки, каждый на отдельной строке.

Напишите программу, которая для каждого магазина находит, какие продукты в нем продаются дешевле, чем в других магазинах, и выводит результат в следующем формате:

Десяточка: 
<продукт1>, <продукт2>, ...
Кубит: 
<продукт3>, <продукт4>, ...
Полоса:
<продукт5>, <продукт6>, ...

                  
Для каждого магазина продукты должны идти на одной строке, разделенные запятой, в исходном порядке следования (при поступлении на вход). Если в каком-то магазине нет ни одного из искомых продуктов или их цена не является минимальной, то укажите для него символ –.

Формат входных данных
На вход программе подается натуральное число n, а затем n строк.

Формат выходных данных
Программа должна вывести текст в соответствии с условием задачи.

Примечание 1. Гарантируется, что цена на один и тот же продукт во всех магазинах разная.

Примечание 2. Гарантируется, что каждый продукт присутствует хотя бы в одном магазине.
"""
def grocery(filename):
    with open(filename, 'r', encoding='utf-8') as file:
        lines = file.readlines()
        grocery_list = []
        d = {}
        for line in lines:
            grocery_list.append(line.strip().split(': '))
        for el in grocery_list:
            d[el[0]] = int(el[1])

        return d
desyatochka = grocery("desyatochka.txt")
kubit = grocery("kubit.txt")
polosa = grocery("polosa.txt")

n = int(input())
products = [input() for _ in range(n)]

best_products = {
        'Десяточка': [],
        'Кубит': [],
        'Полоса': []
    }

for el in products:
    l = []
    if el in desyatochka:
        l.append(("Десяточка", desyatochka[el]))
    if el in kubit:
        l.append(("Кубит", kubit[el]))
    if el in polosa:
        l.append(("Полоса", polosa[el]))

    min_price = min(l, key=lambda x: x[1])
    best_products[min_price[0]].append(el)


for shop, products in best_products.items():
    print(f"{shop}:\n{', '.join(products) if products else '–'}")
