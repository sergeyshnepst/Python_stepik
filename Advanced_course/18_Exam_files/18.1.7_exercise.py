"""
Транслитерация – передача знаков одной письменности знаками другой письменности, при которой каждый знак (или последовательность знаков) одной системы письма передается соответствующим знаком (или последовательностью знаков) другой системы письма.

Напишите функцию transliterate(), которая принимает название текстового файла и производит транслитерацию его содержимого, то есть заменяет кириллические символы на латинские в соответствии с предложенной таблицей. Все остальные символы надо оставить без изменений. Результат транслитерации требуется записать в файл transliteration.txt.

Примечание 1. Обратите внимание на то, что заглавные буквы должны заменяться на соответствующие им заглавные же буквы. Но если транслитерационная последовательность состоит из нескольких символов, то заглавным будет только первый из них: «С» на «S», а «Я» на «Ya».
"""
def transliterate(filename):
    with open(filename, 'r', encoding='utf-8') as text_file:
        text = text_file.read()
        for cyrillic, latin in zip(
            'абвгдеёжзийклмнопрстуфхцчшщъыьэюя',
            ['a', 'b', 'v', 'g', 'd', 'e', 'jo', 'zh', 'z', 'i', 'j', 'k', 'l', 'm', 'n', 'o', 'p', 'r', 's', 't',
            'u', 'f', 'h', 'c', 'ch', 'sh', 'shh', '*', 'y', '\'', 'je', 'ju', 'ya']):
            text = text.replace(cyrillic, latin).replace(cyrillic.upper(), latin.capitalize())
    with open('transliteration.txt', 'w', encoding='utf-8') as output_file:
        return output_file.write(text)