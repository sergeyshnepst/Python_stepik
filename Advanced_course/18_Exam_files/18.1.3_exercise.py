"""
Вам доступен текстовый файл, содержащий оценки студентов за три теста: по одному в каждом триместре. Каждая строка файла записана в следующем формате:

<фамилия> <оценка1> <оценка2> <оценка3>
                  
Тест считается сданным, если количество баллов по нему не меньше 65. Напишите программу для подсчета количества студентов, сдавших все три теста.

Формат входных данных
На вход программе подается строка текста с именем существующего текстового файла.

Формат выходных данных
Программа должна вывести целое число — количество студентов, сдавших все три теста.


"""

with open(input(), 'r', encoding='utf-8') as file:
    lines = file.readlines()
    count = 0
    for line in lines:
        lname, *grades = line.split()
        grades = list(map(int, grades))
        if all(grade >= 65 for grade in grades):
            count += 1

    print(count)
