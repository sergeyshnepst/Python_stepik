"""
Вам доступен текстовый файл с данными о продажах фирмы за месяц. Каждая строка этого файла записана в следующем формате:

$<стоимость покупки>
        
где <стоимость покупки> – целое число.

Напишите программу, которая принимает на вход название файла, подсчитывает суммарную месячную выручку фирмы и выводит результат в следующем формате:

$<суммарная месячная выручка>
                  
Формат входных данных
На вход программе подается строка текста с именем существующего текстового файла.

Формат выходных данных
Программа должна вывести выручку фирмы в соответствии с условием задачи.
"""

with open(input(), 'r', encoding='utf-8') as file:
    lines = file.readlines()
    result = []
    for line in lines:
        line = line[1:].strip()
        result.append(int(line))

    print(f"${sum(result)}")
