"""
На вход программе подаются две строки текста с именами текстовых файлов. Первый файл содержит некоторый текст. Второй файл содержит запрещенные слова в нижнем регистре, разделенные символом пробела. Напишите программу, выводящую на экран содержимое первого файла, но с заменой всех запрещенных слов из второго файла звездочками * (количество звездочек равно количеству букв в слове).

Формат входных данных
На вход программе подается две строки текста с названиями существующих текстовых файлов, каждое на отдельной строке.

Формат выходных данных
Программа должна вывести текст в соответствии с условием задачи.

Примечание 1. Ваша программа должна заменить запрещенные слова, где бы они ни встречались, даже в середине другого слова.

Примечание 2. Программа должна заменять запрещенные слова независимо от их регистра. Например, если второй файл содержит запрещенное слово exam, то слова exam, Exam, ExaM, EXAM и подобные должны быть заменены на ****.
"""

with open(input(), 'r', encoding='utf-8') as text_file, open(input(), 'r', encoding='utf-8') as forbidden_file:
    text = text_file.read()
    forbidden_words = forbidden_file.read().split()
    lower_text = text.lower()
    for word in forbidden_words:
        lower_text = lower_text.replace(word, '*' * len(word))
    
    result = ''
    for i in range(len(text)):
        if lower_text[i] == '*':
            result += '*'
        else:
            result += text[i]
    print(result)