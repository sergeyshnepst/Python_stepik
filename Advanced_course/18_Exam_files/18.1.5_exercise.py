"""
На вход программе подается строка текста с именем текстового файла. Напишите программу, выводящую на экран последние 10 строк этого файла.

Формат входных данных
На вход программе подается строка текста с именем существующего текстового файла.

Формат выходных данных
Программа должна вывести последние 10 строк указанного файла.

Примечание 1. Считайте, что исполняемая программа и указанный файл находятся в одной папке.

Примечание 2. Если количество строк в файле меньше 10, необходимо вывести содержимое файла полностью.

Примечание 3. Подумайте над ситуацией, когда файл очень большой и нерационально считывать все его содержимое в память компьютера.
"""

with open(input(), 'r', encoding='utf-8') as file:
    lines = file.readlines()
    result = []
    for line in lines[-10:]:
        result.append(line.strip())
    for line in result:
        print(line)
